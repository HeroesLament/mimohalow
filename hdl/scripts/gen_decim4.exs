# Generates lib/mimo_halow/hw/rx/decim4.ex (MimoHalow.Hw.Rx.Decim4):
# 8 MS/s -> 2 MS/s for the four receive streams (I/Q of two chains).
# Coefficients come from the model, so this script writes them in.
#
#   mix run scripts/gen_decim4.exs
#
# Spec: MimoHalow.Model.Fixed.Decim4.
alias MimoHalow.Model.Fixed.Decim4

h1 = Decim4.h1()
h2 = Decim4.h2()
c1 = div(length(h1) - 1, 2)
c2 = div(length(h2) - 1, 2)
# Symmetric pairs (k, n-1-k) with non-zero coefficients, k < centre.
p1 = for k <- 0..(c1 - 1), Enum.at(h1, k) != 0, do: {k, length(h1) - 1 - k, Enum.at(h1, k)}
p2 = for k <- 0..(c2 - 1), Enum.at(h2, k) != 0, do: {k, length(h2) - 1 - k, Enum.at(h2, k)}
16 = length(p2) + 1
streams = ~w(i0 q0 i1 q1)
n1 = length(h1)

# Signed coefficient as an EHDL constant of width w (two's complement).
sc = fn v, w -> if v < 0, do: v + Bitwise.bsl(1, w), else: v end

hb1_decls =
  Enum.flat_map(streams, fn s ->
    Enum.map(0..(n1 - 1), &"  wire :x#{s}_#{&1}, 12, init: 0") ++
      Enum.flat_map(p1, fn {a, b, _} -> ["  wire :ps#{s}_#{a}, 30", "  wire :pp#{s}_#{a}, 30"] end) ++
      ["  wire :xc#{s}, 30", "  wire :acc1#{s}, 30", "  wire :r1#{s}, 30", "  wire :y1#{s}, 13, init: 0", "  wire :y1c#{s}, 13"]
  end)

sx = fn sig, w, to -> "{replicate(#{sig}[#{w - 1}..#{w - 1}], #{to - w}), #{sig}}" end

hb1_comb =
  Enum.flat_map(streams, fn s ->
    Enum.flat_map(p1, fn {a, b, c} ->
      ["    ps#{s}_#{a} = #{sx.("x#{s}_#{a}", 12, 30)} + #{sx.("x#{s}_#{b}", 12, 30)}",
       "    pp#{s}_#{a} = ps#{s}_#{a} * #{sc.(c, 30)}"]
    end) ++
      ["    xc#{s} = {#{sx.("x#{s}_#{c1}", 12, 16)}, zero16[13..0]}",
       "    acc1#{s} = " <> Enum.map_join(p1, " + ", fn {a, _, _} -> "pp#{s}_#{a}" end) <> " + xc#{s}",
       "    r1#{s} = acc1#{s} + 16384",
       # sat13 of r1 >> 15: bits 29..27 must all equal bit 27
       "    y1c#{s} = if r1#{s}[29..27] == 0 or r1#{s}[29..27] == 7 do r1#{s}[27..15] else (if r1#{s}[29..29] == 1 do 4096 else 4095 end) end"]
  end)

shift =
  Enum.flat_map(streams, fn s ->
    ["        x#{s}_0 = #{s}"] ++ Enum.map(1..(n1 - 1), &"        x#{s}_#{&1} = x#{s}_#{&1 - 1}")
  end)

hb2_decls =
  Enum.flat_map(streams, fn s ->
    ["  memory :ra#{s}, width: 13, depth: 64, sync_read: :clk, init: #{inspect(List.duplicate(0, 64))}",
     "  memory :rb#{s}, width: 13, depth: 64, sync_read: :clk, init: #{inspect(List.duplicate(0, 64))}",
     "  wire :da#{s}, 13", "  wire :db#{s}, 13", "  wire :pre#{s}, 14", "  wire :pu#{s}, 32", "  wire :pka#{s}, 32", "  wire :pkb#{s}, 32",
     "  wire :ps2#{s}, 32", "  wire :prod#{s}, 40", "  wire :acc2#{s}, 40, init: 0",
     "  wire :r2#{s}, 40", "  wire :y2c#{s}, 12", "  wire :o#{s}, 12, init: 0"]
  end)

coef_arms = p2 |> Enum.with_index() |> Enum.flat_map(fn {{a, b, c}, j} -> ["      #{j} ->", "        ka = #{a}", "        kb = #{b}", "        cf = #{sc.(c, 18)}"] end)
coef_arms = coef_arms ++ ["      15 ->", "        ka = #{c2}", "        kb = #{c2}", "        cf = 65536"]

hb2_comb =
  Enum.flat_map(streams, fn s ->
    ["    da#{s} = ra#{s}[aa]", "    db#{s} = rb#{s}[ab]",
     "    pre#{s} = if dj == 15 do #{sx.("da#{s}", 13, 14)} else #{sx.("da#{s}", 13, 14)} + #{sx.("db#{s}", 13, 14)} end",
     # signed 14 x 18 -> 32 from the unsigned product (one DSP48E1)
     "    pu#{s} = pre#{s} * dcf",
     "    pka#{s} = if pre#{s}[13..13] == 1 do {dcf, zero16[13..0]} else 0 end",
     "    pkb#{s} = if dcf[17..17] == 1 do {pre#{s}, zero16, zero16[1..0]} else 0 end",
     "    ps2#{s} = pu#{s} - pka#{s} - pkb#{s}",
     "    prod#{s} = #{sx.("ps2#{s}", 32, 40)}",
     "    r2#{s} = acc2#{s} + 65536",
     # sat12 of r2 >> 17: bits 39..28 all equal
     "    y2c#{s} = if r2#{s}[39..28] == 0 or r2#{s}[39..28] == 4095 do r2#{s}[28..17] else (if r2#{s}[39..39] == 1 do 2048 else 2047 end) end"]
  end)

ring_write = Enum.flat_map(streams, fn s -> ["        ra#{s}[wp] = y1#{s}", "        rb#{s}[wp] = y1#{s}"] end)
acc_up = Enum.flat_map(streams, fn s -> ["        acc2#{s} = if dj == 0 do prod#{s} else acc2#{s} + prod#{s} end"] end)
y1_latch = Enum.map(streams, &"        y1#{&1} = y1c#{&1}")
outs = Enum.map(streams, &"        o#{&1} = y2c#{&1}")
out_assign = Enum.map(streams, &"    o_#{&1} = o#{&1}")

src = ~S'''
defmodule MimoHalow.Hw.Rx.Decim4 do
  @moduledoc """
  Receive decimator, 8 MS/s -> 2 MS/s, for the four streams (I, Q of both
  chains) in lock step. GENERATED by `scripts/gen_decim4.exs`; edit the
  generator. Bit-exact twin of `MimoHalow.Model.Fixed.Decim4`.

  * HB1 (@@N1@@ taps, Q15): shift register per stream; on every odd input
    (`valid` index, from 0 at `enable`) the @@NP1@@ symmetric pre-add
    products and the centre, rounded, saturated to 13 bits.
  * HB2 (@@N2@@ taps, Q17): HB1 outputs into a 64-deep ring (two copies,
    two reads per cycle); on every odd HB1 output a 16-cycle pre-add MAC
    (15 pairs + centre), one multiplier per stream, rounded, saturated to
    12 bits -> `o_valid` with the four outputs.

  Products: HB1 by constants at 30 bits (sign-extended operands, exact mod
  2^30, |sum| < 2^28); HB2 as a signed 14 x 18 product from the unsigned one
  (`u - (a<0 ? b<<14 : 0) - (b<0 ? a<<18 : 0)`, exact mod 2^32), one
  DSP48E1 per stream. (40 x 40 sign-extended products went to fabric:
  ~6,200 carry bits and ~25k feed LUTs on the board top.)

  `valid` exactly every 4 cycles or slower (8 MS/s on the 32 MHz
  DATA_CLK): HB2 jobs then start at least 16 cycles apart; a job's last
  product and the next job's first address overlap by design.
  """

  use Hw.Component

  clock :clk, freq: 32.0

  input :enable, 1
  input :valid, 1
  input :i0, 12
  input :q0, 12
  input :i1, 12
  input :q1, 12

  output :o_valid, 1
  output :o_i0, 12
  output :o_q0, 12
  output :o_i1, 12
  output :o_q1, 12

  wire :zero16, 16
  wire :ph1, 1, init: 0
  wire :v1, 1, init: 0
  wire :v2, 1, init: 0
  wire :ph2, 1, init: 0
  wire :wp, 6, init: 0
  wire :m, 6, init: 0
  wire :busy, 1, init: 0
  wire :j, 4, init: 0
  wire :ka, 6
  wire :kb, 6
  wire :cf, 18
  wire :aa, 6
  wire :ab, 6
  wire :dv, 1, init: 0
  wire :dj, 4, init: 0
  wire :dcf, 18, init: 0
  wire :fin, 1, init: 0
  wire :ov, 1, init: 0
@@HB1_DECLS@@
@@HB2_DECLS@@

  comb do
    zero16 = 0
@@HB1_COMB@@

    ka = 0
    kb = 0
    cf = 0
    case j do
@@COEF@@
    end
    aa = m - ka
    ab = m - kb
@@HB2_COMB@@

    o_valid = ov
@@OUT_ASSIGN@@
  end

  on :clk do
    v1 = 0
    v2 = 0
    dv = 0
    ov = 0
    fin = 0

    # HB1: shift on every input; compute on odd ones (next cycle, from the new register state).
    if enable == 1 and valid == 1 do
@@SHIFT@@
      if ph1 == 1 do
        v1 = 1
      end
      ph1 = bnot(ph1)
    end
    if v1 == 1 do
@@Y1_LATCH@@
      v2 = 1
    end

    if busy == 1 do
      dv = 1
      dj = j
      dcf = cf
      j = j + 1
      if j == 15 do
        busy = 0
      end
    end
    # HB2: ring write; job on odd HB1 outputs. After the issue block: a job
    # starting on the edge the previous one issues its last address must win.
    if v2 == 1 do
@@RING_WRITE@@
      wp = wp + 1
      if ph2 == 1 do
        busy = 1
        j = 0
        m = wp
      end
      ph2 = bnot(ph2)
    end
    if dv == 1 do
@@ACC_UP@@
      if dj == 15 do
        fin = 1
      end
    end
    if fin == 1 do
      ov = 1
@@OUTS@@
    end
  end
end
'''

src =
  src
  |> String.replace("@@N1@@", Integer.to_string(length(h1)))
  |> String.replace("@@NP1@@", Integer.to_string(length(p1)))
  |> String.replace("@@N2@@", Integer.to_string(length(h2)))
  |> String.replace("@@HB1_DECLS@@", Enum.join(hb1_decls, "\n"))
  |> String.replace("@@HB2_DECLS@@", Enum.join(hb2_decls, "\n"))
  |> String.replace("@@HB1_COMB@@", Enum.join(hb1_comb, "\n"))
  |> String.replace("@@COEF@@", Enum.join(coef_arms, "\n"))
  |> String.replace("@@HB2_COMB@@", Enum.join(hb2_comb, "\n"))
  |> String.replace("@@OUT_ASSIGN@@", Enum.join(out_assign, "\n"))
  |> String.replace("@@SHIFT@@", Enum.join(shift, "\n"))
  |> String.replace("@@Y1_LATCH@@", Enum.join(y1_latch, "\n"))
  |> String.replace("@@RING_WRITE@@", Enum.join(ring_write, "\n"))
  |> String.replace("@@ACC_UP@@", Enum.join(acc_up, "\n"))
  |> String.replace("@@OUTS@@", Enum.join(outs, "\n"))

out = Path.expand("../lib/mimo_halow/hw/rx/decim4.ex", __DIR__)
File.write!(out, src)
IO.puts("wrote #{out} (#{src |> String.split("\n") |> length()} lines)")
