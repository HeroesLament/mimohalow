# Generates lib/mimo_halow/hw/rx/data_demap.ex (MimoHalow.Hw.Rx.DataDemap):
# Cpe DATA points -> soft pairs for Hw.Rx.Viterbi. Per-MCS tables and the
# deinterleaver ROM come from the model, so this script writes them.
#
#   mix run scripts/gen_data_demap.exs
#
# Spec: MimoHalow.Model.Fixed.DataDec.pairs/3 (S1G 2 MHz).
import Bitwise
alias MimoHalow.Model.Fixed.DataDec
alias MimoHalow.Model.Qam
alias MimoHalow.Model.S1g.{Coding, Params}

mods = [:bpsk, :qpsk, :qam16, :qam64, :qam256]
modcode = mods |> Enum.with_index() |> Map.new()
rates = %{{1, 2} => 0, {2, 3} => 1, {3, 4} => 2, {5, 6} => 3}
ndata = length(Params.data(2))

# Puncture patterns over steps: {keepA, keepB} per step of the period.
keep_steps = fn rate -> rate |> Coding.keep() |> Enum.chunk_every(2) end
pat = Map.new(rates, fn {r, code} -> {code, keep_steps.(r)} end)
period_arms =
  Enum.flat_map(pat, fn {code, steps} ->
    ["      #{code} ->", "        pper = #{length(steps) - 1}"]
  end)
keep_arms =
  Enum.flat_map(pat, fn {code, steps} ->
    steps
    |> Enum.with_index()
    |> Enum.flat_map(fn {[ka, kb], i} -> ["      #{code * 8 + i} ->", "        kA = #{ka}", "        kB = #{kb}"] end)
  end)

# MCS table.
mcs_arms =
  Enum.flat_map(0..8, fn m ->
    {:ok, r} = Params.rate(2, m)
    cs = DataDec.consts(r.mod) ++ [0, 0, 0]
    ["      #{m} ->", "        t_mod = #{modcode[r.mod]}", "        t_nbpsc = #{r.nbpsc}", "        t_rate = #{rates[r.rate]}",
     "        t_ndbps = #{r.ndbps}", "        t_smod = #{DataDec.smod(r.mod)}",
     "        t_c1 = #{Enum.at(cs, 0)}", "        t_c2 = #{Enum.at(cs, 1)}", "        t_c3 = #{Enum.at(cs, 2)}"]
  end)

# Deinterleaver ROM: {mod, c} -> {d (6), lane (3)}.
rom =
  for code <- 0..7, c <- 0..511 do
    if code < 5 do
      nb = Qam.nbpsc(Enum.at(mods, code))
      ncbps = ndata * nb
      if c < ncbps do
        p = Enum.at(Coding.perm(Params.interleaver(2, nb), nb, ncbps), c)
        div(p, nb) <<< 3 ||| rem(p, nb)
      else
        0
      end
    else
      0
    end
  end

# Lane assignment per modulation: list of {axis (0 x / 1 y), level k}.
lanes = fn
  :bpsk -> [{0, 0}]
  mod -> m = div(Qam.nbpsc(mod), 2); (for k <- 0..(m - 1), do: {0, k}) ++ for(k <- 0..(m - 1), do: {1, k})
end
lane_arms =
  mods
  |> Enum.with_index()
  |> Enum.flat_map(fn {mod, code} ->
    ls = lanes.(mod) ++ List.duplicate(nil, 8 - length(lanes.(mod)))
    ["      #{code} ->"] ++
      (ls |> Enum.with_index() |> Enum.map(fn
        {nil, i} -> "        lv#{i} = zero28"
        {{ax, k}, i} -> "        lv#{i} = #{if ax == 0, do: "lx", else: "ly"}#{k}"
      end))
  end)

# -L >> q, then clamp +-31 -> 6 bits (per lane).
ashr = fn sig, w, i -> if i == 0, do: sig, else: "{replicate(#{sig}[#{w - 1}..#{w - 1}], #{i}), #{sig}[#{w - 1}..#{i}]}" end
soft_lane = fn i ->
  shift_arms = Enum.flat_map(0..27, fn n -> ["      #{n} ->", "        ns#{i} = #{ashr.("ng#{i}", 28, n)}"] end)
  ["    ng#{i} = zero28 - lv#{i}", "    ns#{i} = ng#{i}", "    case qq do"] ++ shift_arms ++ ["    end",
   "    so#{i} = if ns#{i}[27..27] == 0 and ns#{i}[26..5] != 0 do 31 else (if ns#{i}[27..27] == 1 and (ns#{i}[26..5] != 4194303 or ns#{i}[4..0] == 0) do 33 else ns#{i}[5..0] end) end"]
end
soft_decls = Enum.flat_map(0..7, fn i -> ["  wire :lv#{i}, 28", "  wire :ng#{i}, 28", "  wire :ns#{i}, 28", "  wire :so#{i}, 6"] end)
soft_comb = Enum.flat_map(0..7, soft_lane)
pack = "{" <> Enum.map_join(7..0//-1, ", ", &"so#{&1}") <> "}"
lsel = fn out, word, lane ->
  ["    #{out} = #{word}[5..0]", "    case #{lane} do"] ++
    Enum.flat_map(0..7, fn i -> ["      #{i} ->", "        #{out} = #{word}[#{6 * i + 5}..#{6 * i}]"] end) ++ ["    end"]
end

# q = max(0, bitlen(gsum >> 6) - 4 - smod): bit b of gsum (b >= 6) -> bitlen b - 5.
blen = Enum.reduce(6..27, "0", fn b, acc -> "if gsum[#{b}..#{b}] == 1 do #{b - 5} else (#{acc}) end" end)

src = ~S'''
defmodule MimoHalow.Hw.Rx.DataDemap do
  @moduledoc """
  S1G 2 MHz DATA front of the back end: `Cpe` points -> soft pairs for
  `Hw.Rx.Viterbi`. GENERATED by `scripts/gen_data_demap.exs`; edit the
  generator. Bit-exact twin of `MimoHalow.Model.Fixed.DataDec.pairs/3`.

  * SIG symbol 0: `gsum = sum G` over its @@ND@@ tones. On `sig_done` (not
    discarded): MCS parameters latched, `q = max(0, bitlen(gsum >> 6) - 4 -
    smod)`, `ndata` symbols expected.
  * Per DATA tone (`e_j >= 2`), two pipeline stages: thresholds `Tk = (G
    ck) >> 16`, per axis `L0 = -v`, `L1 = |v| - T1`, `Lk = |L(k-1)| - Tk`,
    lanes in bit order, `soft = clamp(-L >> q, -31, 31)`; the 8 x 6-bit
    word into a ping-pong buffer at `{symbol parity, d}` (two copies, one
    per read port). The last tone (d = @@DL@@) marks the symbol ready.
  * Reader, one information bit per cycle: puncture pattern -> keepA,
    keepB; coded indices `c`, `c + keepA` through the deinterleaver ROM
    (`{mod, c}` -> `{d, lane}`), the buffer, the lane select; erasures 0.
    `p_first` on the PPDU's first pair, `p_last` on its last.

  Contains written memories: verified under iverilog only.
  """

  use Hw.Component

  clock :clk, freq: 32.0

  input :enable, 1
  input :e_valid, 1
  input :e_i, 27
  input :e_q, 27
  input :e_g, 21
  input :e_d, 6
  input :e_j, 11
  input :sig_done, 1
  input :sig_discard, 1
  input :f_mcs, 4
  input :f_ndata, 11

  output :p_valid, 1
  output :p_a, 6
  output :p_b, 6
  output :p_first, 1
  output :p_last, 1
  output :q, 5
  output :early, 8

  memory :bufa, width: 48, depth: 128, sync_read: :clk
  memory :bufb, width: 48, depth: 128, sync_read: :clk
  memory :roma, width: 9, depth: 4096, sync_read: :clk, init: @rom
  memory :romb, width: 9, depth: 4096, sync_read: :clk, init: @rom

  wire :zero28, 28
  wire :zero16, 16

  # --- packet parameters ----------------------------------------------------------------
  wire :gsum, 28, init: 0
  wire :act, 1, init: 0
  wire :pmod, 3, init: 0
  wire :pnb, 4, init: 0
  wire :prate, 2, init: 0
  wire :pndbps, 9, init: 0
  wire :pc1, 17, init: 0
  wire :pc2, 17, init: 0
  wire :pc3, 17, init: 0
  wire :qq, 5, init: 0
  wire :nleft, 11, init: 0
  wire :firstp, 1, init: 0
  wire :early_c, 8, init: 0
  wire :t_mod, 3
  wire :t_nbpsc, 4
  wire :t_rate, 2
  wire :t_ndbps, 9
  wire :t_smod, 3
  wire :t_c1, 17
  wire :t_c2, 17
  wire :t_c3, 17
  wire :bl, 5
  wire :q_c, 5

  # --- write side -----------------------------------------------------------------------
  wire :a_v, 1, init: 0
  wire :a_x, 27, init: 0
  wire :a_y, 27, init: 0
  wire :a_g, 21, init: 0
  wire :a_d, 6, init: 0
  wire :a_par, 1, init: 0
  wire :b_v, 1, init: 0
  wire :b_x, 28, init: 0
  wire :b_y, 28, init: 0
  wire :b_d, 6, init: 0
  wire :b_par, 1, init: 0
  wire :b_t1, 28, init: 0
  wire :b_t2, 28, init: 0
  wire :b_t3, 28, init: 0
  wire :pr1, 38
  wire :pr2, 38
  wire :pr3, 38
  wire :ax, 28
  wire :ay, 28
  wire :lx0, 28
  wire :lx1, 28
  wire :lx2, 28
  wire :lx3, 28
  wire :ly0, 28
  wire :ly1, 28
  wire :ly2, 28
  wire :ly3, 28
  wire :alx1, 28
  wire :alx2, 28
  wire :aly1, 28
  wire :aly2, 28
  wire :word, 48
  wire :waddr, 7
  wire :rdy0, 1, init: 0
  wire :rdy1, 1, init: 0
@@SOFT_DECLS@@

  # --- read side ------------------------------------------------------------------------
  wire :rpar, 1, init: 0
  wire :rbusy, 1, init: 0
  wire :rstep, 9, init: 0
  wire :rc, 9, init: 0
  wire :pp, 3, init: 0
  wire :pper, 3
  wire :kA, 1
  wire :kp, 5
  wire :kB, 1
  wire :r_rdy, 1
  wire :ca, 12
  wire :cb, 12
  wire :s0v, 1, init: 0
  wire :s0ka, 1, init: 0
  wire :s0kb, 1, init: 0
  wire :s0f, 1, init: 0
  wire :s0l, 1, init: 0
  wire :s0par, 1, init: 0
  wire :roa, 9
  wire :rob, 9
  wire :s1v, 1, init: 0
  wire :s1ka, 1, init: 0
  wire :s1kb, 1, init: 0
  wire :s1f, 1, init: 0
  wire :s1l, 1, init: 0
  wire :s1la, 3, init: 0
  wire :s1lb, 3, init: 0
  wire :rda, 48
  wire :rdb, 48
  wire :bra, 7
  wire :brb, 7
  wire :s1par, 1, init: 0
  wire :sa, 6
  wire :sb, 6
  wire :ov, 1, init: 0
  wire :oa, 6, init: 0
  wire :ob, 6, init: 0
  wire :of, 1, init: 0
  wire :ol, 1, init: 0

  comb do
    zero28 = 0
    zero16 = 0

    # MCS table (2 MHz, MCS 0..8)
    t_mod = 0
    t_nbpsc = 0
    t_rate = 0
    t_ndbps = 0
    t_smod = 0
    t_c1 = 0
    t_c2 = 0
    t_c3 = 0
    case f_mcs do
@@MCS@@
    end
    bl = @@BLEN@@
    q_c = if bl > {zero16[1..0], t_smod} + 4 do bl - {zero16[1..0], t_smod} - 4 else 0 end

    # stage B (registered thresholds) -> LLRs
    pr1 = a_g * pc1
    pr2 = a_g * pc2
    pr3 = a_g * pc3
    ax = if b_x[27..27] == 1 do zero28 - b_x else b_x end
    ay = if b_y[27..27] == 1 do zero28 - b_y else b_y end
    lx0 = zero28 - b_x
    lx1 = ax - b_t1
    alx1 = if lx1[27..27] == 1 do zero28 - lx1 else lx1 end
    lx2 = alx1 - b_t2
    alx2 = if lx2[27..27] == 1 do zero28 - lx2 else lx2 end
    lx3 = alx2 - b_t3
    ly0 = zero28 - b_y
    ly1 = ay - b_t1
    aly1 = if ly1[27..27] == 1 do zero28 - ly1 else ly1 end
    ly2 = aly1 - b_t2
    aly2 = if ly2[27..27] == 1 do zero28 - ly2 else ly2 end
    ly3 = aly2 - b_t3
    lv0 = zero28
    lv1 = zero28
    lv2 = zero28
    lv3 = zero28
    lv4 = zero28
    lv5 = zero28
    lv6 = zero28
    lv7 = zero28
    case pmod do
@@LANES@@
    end
@@SOFT@@
    word = @@PACK@@
    waddr = {b_par, b_d}

    # read side
    r_rdy = if rpar == 1 do rdy1 else rdy0 end
    pper = 0
    case prate do
@@PERIOD@@
    end
    kA = 0
    kB = 0
    kp = {prate, pp}
    case kp do
@@KEEP@@
    end
    ca = {pmod, rc}
    cb = {pmod, rc + {zero16[7..0], kA}}
    roa = roma[ca]
    rob = romb[cb]
    bra = {s0par, roa[8..3]}
    brb = {s0par, rob[8..3]}
    rda = bufa[bra]
    rdb = bufb[brb]
@@LSELA@@
@@LSELB@@

    p_valid = ov
    p_a = oa
    p_b = ob
    p_first = of
    p_last = ol
    q = qq
    early = early_c
  end

  on :clk do
    a_v = 0
    b_v = 0
    ov = 0
    s0v = 0
    s1v = 0

    if enable == 1 and e_valid == 1 and e_j == 0 do
      if e_d == 0 do
        gsum = {zero16[6..0], e_g}
      else
        gsum = gsum + {zero16[6..0], e_g}
      end
    end
    if enable == 1 and sig_done == 1 do
      if sig_discard == 0 and f_ndata != 0 do
        act = 1
        pmod = t_mod
        pnb = t_nbpsc
        prate = t_rate
        pndbps = t_ndbps
        pc1 = t_c1
        pc2 = t_c2
        pc3 = t_c3
        qq = q_c
        nleft = f_ndata
        firstp = 1
        rpar = 0
        rdy0 = 0
        rdy1 = 0
        rbusy = 0
      else
        act = 0
      end
    end

    # stage A
    if enable == 1 and e_valid == 1 and e_j >= 2 do
      if act == 1 do
        a_v = 1
        a_x = e_i
        a_y = e_q
        a_g = e_g
        a_d = e_d
        a_par = e_j[0..0]
      else
        early_c = early_c + 1
      end
    end
    # stage B
    if a_v == 1 do
      b_v = 1
      b_x = {a_x[26..26], a_x}
      b_y = {a_y[26..26], a_y}
      b_d = a_d
      b_par = a_par
      b_t1 = {zero16[5..0], pr1[37..16]}
      b_t2 = {zero16[5..0], pr2[37..16]}
      b_t3 = {zero16[5..0], pr3[37..16]}
    end
    if b_v == 1 do
      bufa[waddr] = word
      bufb[waddr] = word
      if b_d == @@DL@@ do
        if b_par == 1 do
          rdy1 = 1
        else
          rdy0 = 1
        end
      end
    end

    # reader: s0 issues ROM reads, s1 buffer reads, then the output register
    if rbusy == 0 do
      if act == 1 and r_rdy == 1 do
        rbusy = 1
        rstep = 0
        rc = 0
        pp = 0
      end
    else
      s0v = 1
      s0ka = kA
      s0kb = kB
      s0f = if firstp == 1 and rstep == 0 do 1 else 0 end
      s0l = if nleft == 1 and rstep == pndbps - 1 do 1 else 0 end
      s0par = rpar
      rc = rc + {zero16[7..0], kA} + {zero16[7..0], kB}
      pp = if pp == pper do 0 else pp + 1 end
      if rstep == pndbps - 1 do
        rbusy = 0
        firstp = 0
        if rpar == 1 do
          rdy1 = 0
        else
          rdy0 = 0
        end
        rpar = bnot(rpar)
        nleft = nleft - 1
        if nleft == 1 do
          act = 0
        end
      else
        rstep = rstep + 1
      end
    end
    if s0v == 1 do
      s1v = 1
      s1ka = s0ka
      s1kb = s0kb
      s1f = s0f
      s1l = s0l
      s1la = roa[2..0]
      s1lb = rob[2..0]
      s1par = s0par
    end
    if s1v == 1 do
      ov = 1
      oa = if s1ka == 1 do sa else 0 end
      ob = if s1kb == 1 do sb else 0 end
      of = s1f
      ol = s1l
    end
  end
end
'''

src =
  src
  |> String.replace("  memory :roma, width: 9, depth: 4096, sync_read: :clk, init: @rom", "  @rom #{inspect(rom, limit: :infinity)}\n  memory :roma, width: 9, depth: 4096, sync_read: :clk, init: @rom")
  |> String.replace("@@ND@@", Integer.to_string(ndata))
  |> String.replace("@@DL@@", Integer.to_string(ndata - 1))
  |> String.replace("@@MCS@@", Enum.join(mcs_arms, "\n"))
  |> String.replace("@@BLEN@@", blen)
  |> String.replace("@@LANES@@", Enum.join(lane_arms, "\n"))
  |> String.replace("@@SOFT_DECLS@@", Enum.join(soft_decls, "\n"))
  |> String.replace("@@SOFT@@", Enum.join(soft_comb, "\n"))
  |> String.replace("@@PACK@@", pack)
  |> String.replace("@@PERIOD@@", Enum.join(period_arms, "\n"))
  |> String.replace("@@KEEP@@", Enum.join(keep_arms, "\n"))
  |> String.replace("@@LSELA@@", Enum.join(lsel.("sa", "rda", "s1la"), "\n"))
  |> String.replace("@@LSELB@@", Enum.join(lsel.("sb", "rdb", "s1lb"), "\n"))

out = Path.expand("../lib/mimo_halow/hw/rx/data_demap.ex", __DIR__)
File.write!(out, src)
IO.puts("wrote #{out} (#{src |> String.split("\n") |> length()} lines)")
