# Generates lib/mimo_halow/hw/rx/viterbi.ex (MimoHalow.Hw.Rx.Viterbi), the
# DATA Viterbi: 64 ACS in parallel (one trellis step per cycle), block
# traceback. The ACS array is regular and wide, so this script writes it.
#
#   mix run scripts/gen_viterbi.exs
#
# Spec: MimoHalow.Model.Fixed.DataDec.viterbi/1 (B = 64, D = 96).
import Bitwise

{b, d} = MimoHalow.Model.Fixed.DataDec.depth()
par = fn x -> x |> Integer.digits(2) |> Enum.sum() |> rem(2) end

# For next state s2: predecessors s = (s2 << 1 & 63) | j, j = 0, 1, register w = (u << 6) | s.
trellis =
  for s2 <- 0..63 do
    u = s2 >>> 5

    for j <- 0..1 do
      s = (s2 <<< 1 &&& 63) ||| j
      w = u <<< 6 ||| s
      {s, par.(w &&& 0b1011011), par.(w &&& 0b1111001)}
    end
  end

init = fn s -> if s == 0, do: 0, else: 49152 end

decls =
  Enum.flat_map(0..63, fn s ->
    ["  wire :pm#{s}, 16, init: #{init.(s)}", "  wire :pb#{s}, 16", "  wire :m0_#{s}, 16", "  wire :m1_#{s}, 16",
     "  wire :md#{s}, 16", "  wire :dc#{s}, 1", "  wire :nm#{s}, 16"]
  end)

acs =
  Enum.flat_map(0..63, fn s -> ["    pb#{s} = if c_first == 1 do #{init.(s)} else pm#{s} end"] end) ++
    (trellis
     |> Enum.with_index()
     |> Enum.flat_map(fn {[{s0, a0, b0}, {s1, a1, b1}], s2} ->
       ["    m0_#{s2} = pb#{s0} + bm#{a0}#{b0}", "    m1_#{s2} = pb#{s1} + bm#{a1}#{b1}",
        "    md#{s2} = m0_#{s2} - m1_#{s2}", "    dc#{s2} = md#{s2}[15..15]",
        "    nm#{s2} = if dc#{s2} == 1 do m1_#{s2} else m0_#{s2} end"]
     end)) ++
    ["    dword = {" <> Enum.map_join(63..0//-1, ", ", &"dc#{&1}") <> "}"]

pm_update = Enum.map(0..63, &"        pm#{&1} = nm#{&1}")
sel_arms = Enum.flat_map(0..63, fn n -> ["      #{n} ->", "        dbit = drd[#{n}..#{n}]"] end)

src = ~S'''
defmodule MimoHalow.Hw.Rx.Viterbi do
  @moduledoc """
  DATA Viterbi decoder: K = 7, 133 / 171, 64 states. GENERATED by
  `scripts/gen_viterbi.exs`; edit the generator. Bit-exact twin of
  `MimoHalow.Model.Fixed.DataDec.viterbi/1`.

  Input: one soft pair per information bit (`in_a`, `in_b`, 6-bit signed,
  positive = coded 1, 0 = erasure), `in_first` / `in_last` marking a
  PPDU's first and last step, into a 512-deep FIFO (plus a one-entry hold
  for the pair in flight when the ACS pauses).

  * ACS, one step per cycle, all 64 states: metric +s / -s per coded bit,
    maximised, 16-bit modular (spreads stay < 2^15), state 0 from 0 and the
    others from -16384 on `in_first`; each state takes its even predecessor
    unless the odd one is strictly greater. Decision words into a 256-deep
    ring.
  * Block traceback (ACS paused; st 1 issues addresses, st 2 drains): after step @@DB1@@ and every @@B@@ steps
    after, from state 0 at the newest step over @@DB@@ steps, keeping the
    oldest @@B@@ bits; at `in_last`, from state 0 (terminated) over every
    step not yet released. One step per cycle; bits into one of two
    reversal banks.
  * Emitter, concurrent with the next ACS run: the bank's bits in step
    order on `out_valid` / `out_bit`, `out_last` on the PPDU's final bit.

  About 3.5 cycles per step (2 MHz MCS8 needs 312 steps per 1280-cycle
  symbol at 32 MHz and 2 MS/s). Contains written memories: verified under
  iverilog only.
  """

  use Hw.Component

  clock :clk, freq: 32.0

  input :enable, 1
  input :in_valid, 1
  input :in_a, 6
  input :in_b, 6
  input :in_first, 1
  input :in_last, 1

  output :out_valid, 1
  output :out_bit, 1
  output :out_last, 1
  output :overflow, 1

  memory :fifo, width: 14, depth: 512, sync_read: :clk
  memory :dmem, width: 64, depth: 256, sync_read: :clk
  memory :rev, width: 1, depth: 512, sync_read: :clk

  wire :zero16, 16

  # --- FIFO --------------------------------------------------------------------------
  wire :wp, 9, init: 0
  wire :rp, 9, init: 0
  wire :cnt, 10, init: 0
  wire :ovf, 1, init: 0
  wire :issue, 1
  wire :fv, 1, init: 0
  wire :frd, 14
  wire :hv, 1, init: 0
  wire :hold, 14, init: 0
  wire :cand_v, 1
  wire :cand, 14
  wire :go, 1

  # --- ACS ---------------------------------------------------------------------------
  wire :c_a, 16
  wire :c_b, 16
  wire :c_first, 1
  wire :c_last, 1
  wire :bm11, 16
  wire :bm10, 16
  wire :bm01, 16
  wire :bm00, 16
  wire :dword, 64
  wire :t, 16, init: 0
  wire :tcur, 16
  wire :nextwin, 16, init: 0
  wire :released, 16, init: 0
@@DECLS@@

  # --- traceback / emit -----------------------------------------------------------------
  wire :st, 2, init: 0
  wire :tk, 16, init: 0
  wire :thi, 16, init: 0
  wire :tlo, 16, init: 0
  wire :nkeep, 16, init: 0
  wire :tv, 1, init: 0
  wire :tkd, 16, init: 0
  wire :ts, 6, init: 0
  wire :tail, 1, init: 0
  wire :drd, 64
  wire :dbit, 1
  wire :rel, 16
  wire :wbank, 1, init: 0
  wire :e_n, 16, init: 0
  wire :e_i, 16, init: 0
  wire :e_bank, 1, init: 0
  wire :e_tail, 1, init: 0
  wire :e_busy, 1, init: 0
  wire :e_rv, 1, init: 0
  wire :e_rlast, 1, init: 0
  wire :raddr, 9
  wire :rrd, 1
  wire :ov, 1, init: 0
  wire :ob, 1, init: 0
  wire :ol, 1, init: 0

  comb do
    zero16 = 0

    issue = if st == 0 and hv == 0 and cnt != 0 do 1 else 0 end
    frd = fifo[rp]
    cand_v = if hv == 1 or fv == 1 do 1 else 0 end
    cand = if hv == 1 do hold else frd end
    go = if st == 0 and cand_v == 1 do 1 else 0 end

    c_first = cand[13..13]
    c_last = cand[12..12]
    c_a = {replicate(cand[11..11], 10), cand[11..6]}
    c_b = {replicate(cand[5..5], 10), cand[5..0]}
    bm11 = c_a + c_b
    bm10 = c_a - c_b
    bm01 = c_b - c_a
    bm00 = zero16 - c_a - c_b
    tcur = if c_first == 1 do 0 else t end
@@ACS@@

    drd = dmem[tk[7..0]]
    dbit = 0
    case ts do
@@SEL@@
    end
    rel = tkd - tlo

    raddr = {e_bank, e_i[7..0]}
    rrd = rev[raddr]

    out_valid = ov
    out_bit = ob
    out_last = ol
    overflow = ovf
  end

  on :clk do
    ov = 0
    tv = 0
    e_rv = 0

    # FIFO write
    if enable == 1 and in_valid == 1 do
      fifo[wp] = {in_first, in_last, in_a, in_b}
      wp = wp + 1
      if cnt == 511 do
        ovf = 1
      end
    end
    if issue == 1 do
      rp = rp + 1
    end
    if issue == 1 and (enable == 0 or in_valid == 0) do
      cnt = cnt - 1
    end
    if issue == 0 and enable == 1 and in_valid == 1 do
      cnt = cnt + 1
    end
    fv = issue

    # Hold: a pair arriving while the ACS is paused, or behind a held one.
    if hv == 1 and go == 1 do
      if fv == 1 do
        hold = frd
      else
        hv = 0
      end
    end
    if st != 0 and fv == 1 do
      hold = frd
      hv = 1
    end

    # ACS step
    if go == 1 do
@@PMUP@@
      dmem[tcur[7..0]] = dword
      t = tcur + 1
      if c_first == 1 do
        released = 0
        nextwin = @@DB1@@
      end
      if c_last == 1 do
        st = 1
        tk = tcur
        thi = tcur
        tlo = if c_first == 1 do 0 else released end
        nkeep = 65535
        tail = 1
        ts = 0
      else
        if tcur == nextwin and c_first == 0 do
          st = 1
          tk = tcur
          thi = tcur
          tlo = tcur - @@DB1@@
          nkeep = @@B@@
          tail = 0
          ts = 0
          nextwin = nextwin + @@B@@
        end
      end
    end

    # Traceback: address tk, data (step tkd) one cycle later.
    if st == 1 do
      tv = 1
      tkd = tk
      if tk == tlo do
        st = 2
      else
        tk = tk - 1
      end
    end
    if tv == 1 do
      if rel < nkeep do
        rev[{wbank, rel[7..0]}] = ts[5..5]
      end
      ts = {ts[4..0], dbit}
      if tkd == tlo do
        st = 0
        e_n = if tail == 1 do thi - tlo + 1 else nkeep end
        e_tail = tail
        e_bank = wbank
        e_i = 0
        e_busy = 1
        wbank = bnot(wbank)
        if tail == 0 do
          released = released + @@B@@
        end
      end
    end

    # Emitter: read rev[{bank, i}], output one cycle later.
    if e_busy == 1 do
      e_rv = 1
      e_rlast = if e_i == e_n - 1 do e_tail else 0 end
      e_i = e_i + 1
      if e_i == e_n - 1 do
        e_busy = 0
      end
    end
    if e_rv == 1 do
      ov = 1
      ob = rrd
      ol = e_rlast
    end
  end
end
'''

src =
  src
  |> String.replace("@@DECLS@@", Enum.join(decls, "\n"))
  |> String.replace("@@ACS@@", Enum.join(acs, "\n"))
  |> String.replace("@@SEL@@", Enum.join(sel_arms, "\n"))
  |> String.replace("@@PMUP@@", Enum.join(pm_update, "\n"))
  |> String.replace("@@DB1@@", Integer.to_string(d + b - 1))
  |> String.replace("@@DB@@", Integer.to_string(d + b))
  |> String.replace("@@B@@", Integer.to_string(b))

out = Path.expand("../lib/mimo_halow/hw/rx/viterbi.ex", __DIR__)
File.write!(out, src)
IO.puts("wrote #{out} (#{src |> String.split("\n") |> length()} lines)")
