defmodule MimoHalow.Hw.Rx.SymFeed do
  @moduledoc """
  Symbol feeder between `Hw.LtfSync` and `Hw.Fft64`: openocusync's
  `Hw.SymFeed` (generated by its `scripts/gen_sym_feed.exs`) with preamble
  preemption added; identical to it while no sync arrives during a packet.

  ## Preemption (mimohalow)

  A false detection (a noise edge, a packet's trailing edge) arms the
  feeder, and the original drops every `sync_done` until that phantom
  packet's SIG has come back and its symbols are flushed: about 550
  samples, which swallows a real PPDU starting within ~300 samples of the
  false trigger. Here a `sync_done` while busy re-arms the feeder unless
  the current packet is *locked* (a `set_nsym` accepted for it):

  * `set_nsym` is accepted only once the packet's own SIG symbols are fed
    (`state` 2 with `sym >= 4`, or the flush); a result arriving earlier
    belongs to an abandoned packet and is ignored. Accepting it locks.
  * A symbol cut short is completed with zeros tagged flush (dropped by
    the combiner), one per 8 cycles from 7 cycles after the re-arm: at
    most 64 x 8 cycles = 32 delayed samples, inside the >= 54 before the
    new `t0`, and >= 512 cycles per FFT frame for `BinMerge`.
  * `preempt_count` counts re-arms; `drop_count` still counts syncs that
    arrive while locked, and syncs whose `t0` has passed.

  `Hw.LtfSync`'s `done` (with `sync_td`, `ts_off`, `dphi`) arrives about
  281 samples after the detection, after the first LTF window has gone by,
  and the FFT takes at most one sample per 4 cycles, so there is no
  catching up. SymFeed therefore works on `y` delayed by 256 samples
  (32 us at 8 Msps): a 256 x 26 memory written one cycle after each
  `y_valid` and read at the same pointer, so the word read is the sample
  from 256 strobes earlier. At `done` the delayed stream is near td + 25;
  the first window starts at `t0 = td + 82 + ts_off - 3` (3 samples of
  CP backoff, as the host `Rx`), at least 54 samples later.

  Per delayed sample, from `t0`: phase `phi = (k - t0) dphi` (24-bit
  turns, advanced on every sample, CP included); windows are 128
  contiguous samples (LTF1, LTF2: symbols 0, 1), then 64 of each 80
  (SIG, DATA: symbols 2..), each CP skipped. Fed samples go through
  `Hw.RotTab` by `-(phi >> 8)` on `8 y` (`OcuSync.Phy.SyncFixed.rotate/3`):
  `z`, 18-bit, gain 1.6468, 2 cycles after the feed register.

  `nsym` (symbols to feed, LTF included) defaults to 1028 at each
  `sync_done` and is set by a `set_nsym` pulse (from the SIG decoder);
  after symbol `nsym - 1` one symbol of zeros is fed (`z_flush`) so the
  FFT emits the last one. `z_sym` tags each sample with its symbol index
  (the flush symbol carries `nsym`).

  A `sync_done` while busy, or whose `t0` the delayed stream has already
  passed, is dropped and counted in `drop_count`.

  Contains a written `memory`: the EHDL simulator skips MemWrite, so this
  block is verified under iverilog only (the `Hw.StreamBRAMFIFO`
  exception).
  """

  use Hw.Component

  clock :clk, freq: 32.0

  input :enable, 1
  input :y_valid, 1
  input :y_i, 13
  input :y_q, 13
  input :sync_done, 1
  input :sync_td, 32
  input :ts_off, 6
  input :dphi, 24
  input :set_nsym, 1
  input :nsym, 11

  output :z_valid, 1
  output :z_i, 18
  output :z_q, 18
  output :z_sym, 11
  output :z_flush, 1
  output :busy, 1
  output :drop_count, 16
  output :preempt_count, 16

  memory :dly, width: 26, depth: 256, sync_read: :clk

  wire :zero3, 3
  wire :zero16, 16
  wire :zero18, 18

  # --- W: delay line --------------------------------------------------------
  wire :cnt, 32, init: 0
  wire :yv1, 1, init: 0
  wire :yb, 26, init: 0
  wire :widx, 32, init: 0
  wire :wptr, 8, init: 0
  wire :warm, 1, init: 0
  wire :rd, 26

  # --- A: delayed sample ------------------------------------------------------
  wire :a_v, 1, init: 0
  wire :a_y, 26, init: 0
  wire :a_di, 32, init: 0

  # --- B: control -------------------------------------------------------------
  wire :state, 2, init: 0
  wire :t0, 32, init: 0
  wire :dph, 24, init: 0
  wire :phi, 24, init: 0
  wire :nlim, 11, init: 0
  wire :sym, 11, init: 0
  wire :seg, 7, init: 0
  wire :pre, 1, init: 0
  wire :fm, 6, init: 0
  wire :drops, 16, init: 0
  wire :pres, 16, init: 0
  wire :lock, 1, init: 0
  wire :drn, 1, init: 0
  wire :dcnt, 3, init: 0
  wire :dsym, 11, init: 0
  wire :pre_now, 1
  wire :acc, 1
  wire :dd, 32
  wire :d_zero, 1
  wire :d_past, 1
  wire :sym_n, 11
  wire :lim_hit, 1
  wire :seg_cp, 1
  wire :sym_end, 1

  # --- feed register (CORDIC input) -------------------------------------------
  wire :f_v, 1, init: 0
  wire :f_y, 26, init: 0
  wire :f_phi, 24, init: 0
  wire :f_sym, 11, init: 0
  wire :f_fl, 1, init: 0
  wire :f_x18, 18
  wire :f_y18, 18
  wire :f_ang, 16
  wire :zero7, 7
  wire :zero36, 36
  wire :r_x, 25
  wire :r_y, 25
  wire :r_tag, 48
  wire :r_xo, 27
  wire :r_yo, 27
  wire :r_out_tag, 48

  comb do
    zero3 = 0
    zero7 = 0
    zero36 = 0
    zero16 = 0
    zero18 = 0
    rd = dly[wptr]

    dd = a_di - t0
    d_zero = if dd == 0 do 1 else 0 end
    d_past = if dd[31..31] == 0 do 1 else 0 end
    sym_n = sym + 1
    lim_hit = if sym_n >= nlim do 1 else 0 end
    seg_cp = if seg < 16 do 1 else 0 end
    sym_end = if fm == 63 do 1 else 0 end

    # 8 y, sign-extended to 18 bits; angle -(phi >> 8).
    f_x18 = {replicate(f_y[25..25], 2), f_y[25..13], zero3}
    f_y18 = {replicate(f_y[12..12], 2), f_y[12..0], zero3}
    f_ang = zero16 - f_phi[23..8]
    r_x = {replicate(f_x18[17..17], 7), f_x18}
    r_y = {replicate(f_y18[17..17], 7), f_y18}
    r_tag = {zero36, f_fl, f_sym}

    z_i = r_xo[17..0]
    z_q = r_yo[17..0]
    z_sym = r_out_tag[10..0]
    z_flush = r_out_tag[11..11]
    busy = if state != 0 do 1 else 0 end
    drop_count = drops
    preempt_count = pres
    pre_now = if sync_done == 1 and state != 0 and lock == 0 do 1 else 0 end
    acc = if pre_now == 0 and ((state == 2 and sym >= 4) or state == 3) do 1 else 0 end
  end

  # W: index, buffer, one-cycle-late write (read and write share the edge).
  on :clk do
    yv1 = 0
    if enable == 0 do
      cnt = 0
      warm = 0
      wptr = 0
    else
      if y_valid == 1 do
        yb = {y_i, y_q}
        widx = cnt
        cnt = cnt + 1
        yv1 = 1
      end
      if yv1 == 1 do
        dly[wptr] = yb
        wptr = wptr + 1
        if wptr == 255 do
          warm = 1
        end
      end
    end
  end

  # A: the word read is the sample written 256 strobes before this one.
  on :clk do
    a_v = 0
    if yv1 == 1 and warm == 1 do
      a_v = 1
      a_y = rd
      a_di = widx - 256
    end
  end

  # B: arm on sync_done (or re-arm: preemption), feed windows, drain, flush.
  on :clk do
    f_v = 0
    dcnt = dcnt + 1
    if enable == 0 do
      state = 0
      drops = 0
      pres = 0
      lock = 0
      drn = 0
    else
      if state == 0 and sync_done == 1 do
        t0 = sync_td + zero_extend(ts_off, 32) + 79
        dph = dphi
        nlim = 1028
        lock = 0
        state = 1
      else
       if pre_now == 1 do
        t0 = sync_td + zero_extend(ts_off, 32) + 79
        dph = dphi
        nlim = 1028
        lock = 0
        state = 1
        pres = pres + 1
        if state != 1 and fm != 0 do
          drn = 1
          dsym = sym
          dcnt = 1
        end
       else
        if sync_done == 1 and state != 0 do
          drops = drops + 1
        end
        if a_v == 1 and state == 1 do
          if d_zero == 1 do
            f_v = 1
            f_y = a_y
            f_phi = 0
            f_sym = 0
            f_fl = 0
            phi = dph
            sym = 0
            fm = 1
            seg = 1
            pre = 1
            state = 2
          else
            if d_past == 1 do
              drops = drops + 1
              state = 0
            end
          end
        end
        if a_v == 1 and state == 2 do
          phi = phi + dph
          if pre == 1 or seg_cp == 0 do
            f_v = 1
            f_y = a_y
            f_phi = phi
            f_sym = sym
            f_fl = 0
            fm = fm + 1
            if sym_end == 1 do
              sym = sym_n
              if lim_hit == 1 do
                state = 3
              end
            end
          end
          if pre == 1 do
            if seg == 127 do
              pre = 0
              seg = 0
            else
              seg = seg + 1
            end
          else
            if seg == 79 do
              seg = 0
            else
              seg = seg + 1
            end
          end
        end
        if a_v == 1 and state == 3 do
          f_v = 1
          f_y = 0
          f_phi = 0
          f_sym = sym
          f_fl = 1
          fm = fm + 1
          if sym_end == 1 do
            state = 0
          end
        end
        # Drain a preempted packet's partial symbol (state is 1 meanwhile).
        if drn == 1 and dcnt == 0 do
          f_v = 1
          f_y = 0
          f_phi = 0
          f_sym = dsym
          f_fl = 1
          fm = fm + 1
          if sym_end == 1 do
            drn = 0
          end
        end
       end
      end
      if set_nsym == 1 and acc == 1 do
        nlim = nsym
        lock = 1
      end
    end
  end

  instance :rot, Hw.RotTab,
    clk: :clk,
    in_v: :f_v,
    x: :r_x,
    y: :r_y,
    a: :f_ang,
    tag: :r_tag,
    out_v: :z_valid,
    xo: :r_xo,
    yo: :r_yo,
    out_tag: :r_out_tag
end
