defmodule MimoHalow.Hw.Rx.Cpe do
  @moduledoc """
  Common-phase (pilot) tracking: the stage after the MIMO detector, shared
  by every mode. GENERATED by `scripts/gen_cpe.exs`; edit the generator.
  Bit-exact twin of `MimoHalow.Model.Fixed.Cpe` (S1G 2 MHz).

  Input: the detector's per-tone stream (`MrcCombiner` output): `{D, G}`
  for every used tone of symbol `in_j` (0 = first symbol after LTF1),
  pilots flagged by `in_pilot` with `in_d` the pilot index, data tones with
  `in_d` the data index, `in_last` on the symbol's final tone. Tones of one
  symbol arrive consecutively, symbols at least 128 cycles apart.

  * On the fly: data tones `{sat25(D), G}` into a double buffer (parity
    `j[0]`); `C += v_i(j) D_i` over pilots, `v_i(j)` = base pattern
    rotated by `j - 2` (fixed in the SIG) times polarity `p_j` from
    the 127-periodic LFSR (reset at `j = 0`).
  * On `in_last`: normalise C to 20 significant bits, fold a half turn,
    16 vectoring steps -> `theta`; then the 52 data tones in index order
    through `Hw.RotTab` by `-theta`. Output `e_i/e_q` = D' (gain K =
    1.6468), `e_g` = G, `e_d`, `e_j`, `e_last` on the last data tone,
    `e_theta` the symbol's phase.

  The engine takes at most ~90 cycles. Contains written memories:
  verified under iverilog only.
  """

  use Hw.Component

  clock :clk, freq: 32.0

  input :enable, 1
  input :in_valid, 1
  input :in_i, 26
  input :in_q, 26
  input :in_g, 21
  input :in_d, 6
  input :in_j, 11
  input :in_last, 1
  input :in_pilot, 1

  output :e_valid, 1
  output :e_i, 27
  output :e_q, 27
  output :e_g, 21
  output :e_d, 6
  output :e_j, 11
  output :e_last, 1
  output :e_theta, 16

  memory :dbuf, width: 71, depth: 128, sync_read: :clk

  wire :zero1, 1
  wire :zero2, 2
  wire :zero9, 9
  wire :zero16, 16
  wire :zero28, 28

  # --- stage A: registered input ----------------------------------------------------
  wire :a_v, 1, init: 0
  wire :a_r, 26, init: 0
  wire :a_q, 26, init: 0
  wire :a_g, 21, init: 0
  wire :a_d, 6, init: 0
  wire :a_j, 11, init: 0
  wire :a_last, 1, init: 0
  wire :a_pil, 1, init: 0

  wire :lfsr, 7, init: 127
  wire :lfsr_e, 7
  wire :pfb, 1
  wire :rot, 2
  wire :jm, 11
  wire :pidx, 2
  wire :pneg, 1
  wire :pn, 1
  wire :xr28, 28
  wire :xi28, 28
  wire :cadd_r, 28
  wire :cadd_i, 28
  wire :cnext_r, 28
  wire :cnext_i, 28
  wire :cacc_r, 28, init: 0
  wire :cacc_i, 28, init: 0
  wire :s_r, 25
  wire :s_i, 25
  wire :waddr, 7

  # --- engine -------------------------------------------------------------------
  wire :es, 2, init: 0
  wire :it, 4, init: 0
  wire :vx, 28, init: 0
  wire :vy, 28, init: 0
  wire :vz, 16, init: 0
  wire :ax, 28
  wire :ay, 28
  wire :vm, 28
  wire :v_big, 1
  wire :v_small, 1
  wire :v_at, 16
  wire :v_xs, 28
  wire :v_ys, 28
  wire :opar, 1, init: 0
  wire :oj, 11, init: 0
  wire :od, 6, init: 0
  wire :th, 16, init: 0
  wire :nega, 16

  # --- drain: q (address) -> q2 (read data) -> RotTab ----------------------------------
  wire :q_v, 1, init: 0
  wire :q_d, 6, init: 0
  wire :q2_v, 1, init: 0
  wire :q2_d, 6, init: 0
  wire :q2_j, 11, init: 0
  wire :raddr, 7
  wire :rd, 71
  wire :r_x, 25
  wire :r_y, 25
  wire :r_tag, 48
  wire :r_xo, 27
  wire :r_yo, 27
  wire :r_out_tag, 48
  wire :r_ov, 1

  comb do
    zero1 = 0
    zero2 = 0
    zero9 = 0
    zero16 = 0
    zero28 = 0

    # pilot value v_i(j): pattern rotated by j - nsig (fixed while j < nsig), polarity p_j
    lfsr_e = if a_j == 0 do 127 else lfsr end
    pfb = bxor(lfsr_e[6..6], lfsr_e[3..3])
    jm = a_j - 2
    rot = if a_j < 2 do 0 else jm[1..0] end
    pidx = a_d[1..0] + rot
    pneg = if pidx == 3 do 1 else 0 end
    pn = bxor(pneg, pfb)
    xr28 = {replicate(a_r[25..25], 2), a_r}
    xi28 = {replicate(a_q[25..25], 2), a_q}
    cadd_r = if a_pil == 1 do (if pn == 1 do zero28 - xr28 else xr28 end) else zero28 end
    cadd_i = if a_pil == 1 do (if pn == 1 do zero28 - xi28 else xi28 end) else zero28 end
    cnext_r = cacc_r + cadd_r
    cnext_i = cacc_i + cadd_i

    # symmetric sat25 (|x| < 2^24 for the rotator)
    s_r = if a_r[25..24] == 1 do 16777215 else (if a_r[25..24] == 2 or (a_r[25..24] == 3 and a_r[23..0] == 0) do 16777217 else a_r[24..0] end) end
    s_i = if a_q[25..24] == 1 do 16777215 else (if a_q[25..24] == 2 or (a_q[25..24] == 3 and a_q[23..0] == 0) do 16777217 else a_q[24..0] end) end
    waddr = {a_j[0..0], a_d}

    ax = if vx[27..27] == 1 do zero28 - vx else vx end
    ay = if vy[27..27] == 1 do zero28 - vy else vy end
    vm = bor(ax, ay)
    v_big = if vm[27..20] != 0 do 1 else 0 end
    v_small = if vm[27..19] == 0 and vm != 0 do 1 else 0 end
    v_at = 0
    case it do
      0 ->
        v_at = 8192
      1 ->
        v_at = 4836
      2 ->
        v_at = 2555
      3 ->
        v_at = 1297
      4 ->
        v_at = 651
      5 ->
        v_at = 326
      6 ->
        v_at = 163
      7 ->
        v_at = 81
      8 ->
        v_at = 41
      9 ->
        v_at = 20
      10 ->
        v_at = 10
      11 ->
        v_at = 5
      12 ->
        v_at = 3
      13 ->
        v_at = 1
      14 ->
        v_at = 1
      15 ->
        v_at = 0
    end
    v_xs = vx
    case it do
      0 ->
        v_xs = vx
      1 ->
        v_xs = {replicate(vx[27..27], 1), vx[27..1]}
      2 ->
        v_xs = {replicate(vx[27..27], 2), vx[27..2]}
      3 ->
        v_xs = {replicate(vx[27..27], 3), vx[27..3]}
      4 ->
        v_xs = {replicate(vx[27..27], 4), vx[27..4]}
      5 ->
        v_xs = {replicate(vx[27..27], 5), vx[27..5]}
      6 ->
        v_xs = {replicate(vx[27..27], 6), vx[27..6]}
      7 ->
        v_xs = {replicate(vx[27..27], 7), vx[27..7]}
      8 ->
        v_xs = {replicate(vx[27..27], 8), vx[27..8]}
      9 ->
        v_xs = {replicate(vx[27..27], 9), vx[27..9]}
      10 ->
        v_xs = {replicate(vx[27..27], 10), vx[27..10]}
      11 ->
        v_xs = {replicate(vx[27..27], 11), vx[27..11]}
      12 ->
        v_xs = {replicate(vx[27..27], 12), vx[27..12]}
      13 ->
        v_xs = {replicate(vx[27..27], 13), vx[27..13]}
      14 ->
        v_xs = {replicate(vx[27..27], 14), vx[27..14]}
      15 ->
        v_xs = {replicate(vx[27..27], 15), vx[27..15]}
    end
    v_ys = vy
    case it do
      0 ->
        v_ys = vy
      1 ->
        v_ys = {replicate(vy[27..27], 1), vy[27..1]}
      2 ->
        v_ys = {replicate(vy[27..27], 2), vy[27..2]}
      3 ->
        v_ys = {replicate(vy[27..27], 3), vy[27..3]}
      4 ->
        v_ys = {replicate(vy[27..27], 4), vy[27..4]}
      5 ->
        v_ys = {replicate(vy[27..27], 5), vy[27..5]}
      6 ->
        v_ys = {replicate(vy[27..27], 6), vy[27..6]}
      7 ->
        v_ys = {replicate(vy[27..27], 7), vy[27..7]}
      8 ->
        v_ys = {replicate(vy[27..27], 8), vy[27..8]}
      9 ->
        v_ys = {replicate(vy[27..27], 9), vy[27..9]}
      10 ->
        v_ys = {replicate(vy[27..27], 10), vy[27..10]}
      11 ->
        v_ys = {replicate(vy[27..27], 11), vy[27..11]}
      12 ->
        v_ys = {replicate(vy[27..27], 12), vy[27..12]}
      13 ->
        v_ys = {replicate(vy[27..27], 13), vy[27..13]}
      14 ->
        v_ys = {replicate(vy[27..27], 14), vy[27..14]}
      15 ->
        v_ys = {replicate(vy[27..27], 15), vy[27..15]}
    end
    nega = zero16 - th

    raddr = {opar, q_d}
    rd = dbuf[raddr]
    r_x = rd[70..46]
    r_y = rd[45..21]
    r_tag = {zero9, rd[20..0], q2_j, q2_d, zero1}

    e_valid = r_ov
    e_i = r_xo
    e_q = r_yo
    e_g = r_out_tag[38..18]
    e_j = r_out_tag[17..7]
    e_d = r_out_tag[6..1]
    e_last = if r_out_tag[6..1] == 51 do 1 else 0 end
    e_theta = th
  end

  # A: register one tone.
  on :clk do
    a_v = 0
    if enable == 1 and in_valid == 1 do
      a_v = 1
      a_r = in_i
      a_q = in_q
      a_g = in_g
      a_d = in_d
      a_j = in_j
      a_last = in_last
      a_pil = in_pilot
    end
  end

  on :clk do
    q2_v = q_v
    q2_d = q_d
    q2_j = oj
    q_v = 0

    # A: buffer data, accumulate pilots; the symbol's last tone starts the engine.
    if a_v == 1 do
      if a_pil == 0 do
        dbuf[waddr] = {s_r, s_i, a_g}
      end
      if a_last == 1 do
        vx = cnext_r
        vy = cnext_i
        es = 1
        cacc_r = 0
        cacc_i = 0
        opar = a_j[0..0]
        oj = a_j
        lfsr = {lfsr_e[5..0], pfb}
      else
        cacc_r = cnext_r
        cacc_i = cnext_i
        lfsr = lfsr_e
      end
    end

    # engine 1: normalise to 20 significant bits, then half-turn fold.
    if es == 1 do
      if v_big == 1 do
        vx = {vx[27..27], vx[27..1]}
        vy = {vy[27..27], vy[27..1]}
      else
        if v_small == 1 do
          vx = {vx[26..0], zero1}
          vy = {vy[26..0], zero1}
        else
          if vx[27..27] == 1 do
            vx = zero28 - vx
            vy = zero28 - vy
            vz = 32768
          else
            vz = 0
          end
          it = 0
          es = 2
        end
      end
    end

    # engine 2: 16 vectoring steps.
    if es == 2 do
      if vy[27..27] == 0 do
        vx = vx + v_ys
        vy = vy - v_xs
        vz = vz + v_at
      else
        vx = vx - v_ys
        vy = vy + v_xs
        vz = vz - v_at
      end
      it = it + 1
      if it == 15 do
        es = 3
        od = 0
      end
    end

    # engine 3: latch theta, then read the data tones in index order.
    if es == 3 do
      if od == 0 do
        th = vz
      end
      q_v = 1
      q_d = od
      od = od + 1
      if od == 51 do
        es = 0
      end
    end
  end

  instance :rot, Hw.RotTab,
    clk: :clk,
    in_v: :q2_v,
    x: :r_x,
    y: :r_y,
    a: :nega,
    tag: :r_tag,
    out_v: :r_ov,
    xo: :r_xo,
    yo: :r_yo,
    out_tag: :r_out_tag
end
